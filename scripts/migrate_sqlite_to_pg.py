"""把 SQLite 的 game.db 数据一次性搬到 PostgreSQL。

用法：
    python scripts/migrate_sqlite_to_pg.py                    # game.db -> jubensha 库
    python scripts/migrate_sqlite_to_pg.py --recreate         # 先清空目标库的表再搬
    PG_DSN=postgresql://user:pw@127.0.0.1:5432/jubensha python scripts/migrate_sqlite_to_pg.py
"""

import argparse
import os
import re
import sqlite3

import psycopg

DEFAULT_DSN = "postgresql://rag:rag_dev_2026@127.0.0.1:5432/jubensha"
SKIP_TABLES = {"sqlite_sequence"}
APPEND_ONLY_TABLES = ("game_events",)


def convert_ddl(ddl: str) -> str:
    ddl = ddl.replace("INTEGER PRIMARY KEY AUTOINCREMENT",
                      "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    ddl = re.sub(r"\bREAL\b", "DOUBLE PRECISION", ddl)
    ddl = re.sub(r"\bBLOB\b", "BYTEA", ddl)
    ddl = re.sub(r"\bAUTOINCREMENT\b", "", ddl)
    return ddl.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)


def ensure_database(dsn: str) -> None:
    target = dsn.rsplit("/", 1)[-1].split("?")[0]
    admin_dsn = dsn.rsplit("/", 1)[0] + "/postgres"
    with psycopg.connect(admin_dsn, autocommit=True) as conn:
        exists = conn.execute("SELECT 1 FROM pg_database WHERE datname=%s", (target,)).fetchone()
        if exists:
            print(f"库 {target} 已存在")
            return
        conn.execute(f'CREATE DATABASE "{target}"')
        print(f"已创建库 {target}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sqlite", default=os.getenv("SQLITE_PATH", "game.db"))
    parser.add_argument("--dsn", default=os.getenv("PG_DSN", DEFAULT_DSN))
    parser.add_argument("--recreate", action="store_true", help="先 DROP 目标库里的同名表")
    args = parser.parse_args()

    ensure_database(args.dsn)
    src = sqlite3.connect(args.sqlite)
    src.row_factory = sqlite3.Row

    tables = [(row["name"], row["sql"]) for row in src.execute(
        "SELECT name, sql FROM sqlite_master WHERE type='table' ORDER BY name")
        if row["name"] not in SKIP_TABLES and row["sql"]]

    report = []
    with psycopg.connect(args.dsn) as conn:
        with conn.cursor() as cur:
            for name, ddl in tables:
                if args.recreate:
                    cur.execute(f'DROP TABLE IF EXISTS "{name}" CASCADE')
                cur.execute(convert_ddl(ddl))
            for name, _ in tables:
                columns = [row["name"] for row in src.execute(f'PRAGMA table_info("{name}")')]
                select_list = ",".join(f'"{column}"' for column in columns)
                rows = src.execute(f'SELECT {select_list} FROM "{name}"').fetchall()
                if rows:
                    placeholders = ",".join(["%s"] * len(columns))
                    quoted = ",".join(f'"{c}"' for c in columns)
                    cur.executemany(
                        f'INSERT INTO "{name}" ({quoted}) VALUES ({placeholders}) ON CONFLICT DO NOTHING',
                        [tuple(row) for row in rows])
                report.append((name, len(rows)))
            for name, _ in tables:
                if any(col["name"] == "id" and "INTEGER" in (col["type"] or "").upper()
                       for col in src.execute(f'PRAGMA table_info("{name}")')):
                    cur.execute(
                        f"SELECT setval(pg_get_serial_sequence('{name}','id'), "
                        f'COALESCE((SELECT max(id) FROM "{name}"), 1), true)')
            if "game_events" in {name for name, _ in tables}:
                cur.execute("""
                    CREATE OR REPLACE FUNCTION game_events_append_only() RETURNS trigger AS $$
                    BEGIN RAISE EXCEPTION 'game_events is append-only'; END;
                    $$ LANGUAGE plpgsql;
                """)
                for action in ("UPDATE", "DELETE"):
                    cur.execute(f"DROP TRIGGER IF EXISTS events_no_{action.lower()} ON game_events")
                    cur.execute(f"CREATE TRIGGER events_no_{action.lower()} BEFORE {action} ON game_events "
                                f"FOR EACH ROW EXECUTE FUNCTION game_events_append_only()")
        conn.commit()

        print(f"{'表名':<24}{'SQLite':>8}{'PostgreSQL':>12}")
        mismatched = []
        with conn.cursor() as cur:
            for name, copied in report:
                cur.execute(f'SELECT count(*) FROM "{name}"')
                actual = cur.fetchone()[0]
                print(f"{name:<24}{copied:>8}{actual:>12}")
                if actual < copied:
                    mismatched.append(name)
        if mismatched:
            raise SystemExit(f"行数不一致：{', '.join(mismatched)}")
        print("迁移完成，行数一致。")


if __name__ == "__main__":
    main()
