APPEND_ONLY_FUNCTION = """
CREATE OR REPLACE FUNCTION game_events_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'game_events is append-only';
END;
$$ LANGUAGE plpgsql;
"""


class Row(dict):
    """同时支持 row["column"] 与 row[0]，兼容原先 sqlite3.Row 的两种写法。"""

    __slots__ = ()

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    names = [column.name for column in cursor.description or []]

    def make(values):
        return Row(zip(names, values))

    return make


def resolve_dsn(value: str | Path | None = None) -> str:
    for candidate in (value, os.getenv("PG_DSN"), os.getenv("GAME_DB"), DEFAULT_DSN):
        if candidate is None:
            continue
        text = str(candidate)
        if text.startswith(("postgres://", "postgresql://")):
            return text
    raise ValueError("需要 PostgreSQL 连接串，例如 PG_DSN=postgresql://user:pw@127.0.0.1:5432/jubensha")


def connect(dsn: str, schema: str | None = None):
    connection = psycopg.connect(dsn, row_factory=_row_factory)
    if schema:
        connection.execute(f'SET search_path TO "{schema}", public')
    return connection


