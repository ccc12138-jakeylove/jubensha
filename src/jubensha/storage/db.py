_prepared: set[tuple[str, str | None]] = set()


def ensure_schema(connection, dsn: str, schema: str | None = None) -> None:
    """幂等建表：同一进程内每个 (dsn, schema) 只建一次。"""
    key = (dsn, schema)
    if key in _prepared:
        return
    with connection.cursor() as cursor:
        if schema:
            cursor.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
        cursor.execute("SELECT pg_advisory_xact_lock(hashtext('jubensha_schema'))")
        for statement in SCHEMA_STATEMENTS:
            cursor.execute(statement)
        cursor.execute(APPEND_ONLY_FUNCTION)
        for action in ("UPDATE", "DELETE"):
            cursor.execute(f"DROP TRIGGER IF EXISTS events_no_{action.lower()} ON game_events")
            cursor.execute(
                f"CREATE TRIGGER events_no_{action.lower()} BEFORE {action} ON game_events "
                f"FOR EACH ROW EXECUTE FUNCTION game_events_append_only()")
    _prepared.add(key)
